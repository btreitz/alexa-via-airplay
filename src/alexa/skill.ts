// Generates the two files of the user's Alexa-hosted skill. It answers every
// launch with AudioPlayer.Play for a freshly signed, short-lived stream URL:
// <public base URL>/play.mp3?d=<device>&exp=<unix>&sig=<HMAC-SHA256(secret, d|exp)>
// and reports the Echo's playback (started, stopped, failed) and the user
// pausing or resuming on the Echo to the bridge, with a signed POST to the
// same path (signing.ts). The bridge uses the reports to pause the sender at
// once after "Alexa, stop" and to measure the Echo's buffer.
//
// The generated code must stay plain: the developer console rejects optional
// chaining and the runtime is Node 16.

import { URL_TTL_SECONDS } from "../public/signing.ts";

/** How long the skill waits for the bridge to take a report. */
export const REPORT_TIMEOUT_MS = 1500;

export interface SkillOptions {
  publicBaseUrl: string;
  secret: string;
  invocationName: string;
}

export function normalizeBaseUrl(input: string): string {
  const url = new URL(input.trim());
  if (url.protocol !== "https:") throw new Error("The public base URL must start with https://");
  if (url.search || url.hash) throw new Error("The public base URL must not contain ? or #");
  if (url.username || url.password) throw new Error("The public base URL must not contain credentials");
  return url.toString().replace(/\/+$/, "");
}

/** Alexa invocation names: lowercase words, at least two, letters and spaces only. */
export function validateInvocationName(input: string): string {
  const name = input.trim().toLowerCase().replace(/\s+/g, " ");
  if (!/^[a-z]+( [a-z]+)+$/.test(name) || name.length > 50) {
    throw new Error("The invocation name needs at least two words, using only letters a–z and spaces");
  }
  if (/\b(alexa|amazon|echo|skill|app)\b/.test(name)) {
    throw new Error("The invocation name must not contain alexa, amazon, echo, skill or app");
  }
  return name;
}

export function streamUrl(publicBaseUrl: string): string {
  return `${normalizeBaseUrl(publicBaseUrl)}/play.mp3`;
}

export function skillIndexJs({ publicBaseUrl, secret }: SkillOptions): string {
  return `// Generated by alexa-via-airplay. Paste into lambda/index.js, then Save and Deploy.
// Every launch answers with AudioPlayer.Play for a short-lived signed URL of
// the bridge's public stream. The skill also tells the bridge when the Echo
// starts or stops playing, so "Alexa, stop" pauses your phone at once.
// Regenerate it when the URL or the secret changes. Keep this code private:
// the secret below lets anyone sign stream URLs.

var crypto = require("crypto");
var https = require("https");

var STREAM_URL = ${JSON.stringify(streamUrl(publicBaseUrl))};
var SECRET = ${JSON.stringify(secret)};
var URL_TTL_SECONDS = ${URL_TTL_SECONDS};
// A report must not hold up the answer to Alexa for long.
var REPORT_TIMEOUT_MS = ${REPORT_TIMEOUT_MS};

function deviceSuffix(event) {
  var system = (event.context && event.context.System) || {};
  var deviceId = (system.device && system.device.deviceId) || "unknown";
  // The last 16 characters are stable per Echo; the bridge maps them to a receiver.
  return deviceId.slice(-16);
}

function hmac(message) {
  return crypto.createHmac("sha256", SECRET).update(message).digest("base64")
    .replace(/\\+/g, "-").replace(/\\//g, "_").replace(/=+$/, "");
}

function signedUrl(event) {
  var d = deviceSuffix(event);
  var exp = Math.floor(Date.now() / 1000) + URL_TTL_SECONDS;
  return STREAM_URL + "?d=" + encodeURIComponent(d) + "&exp=" + exp + "&sig=" + hmac(d + "|" + exp);
}

// Tells the bridge what happened on the Echo. Never fails: the skill works
// the same without the bridge hearing of it.
function report(event, name) {
  var d = deviceSuffix(event);
  var exp = Math.floor(Date.now() / 1000) + URL_TTL_SECONDS;
  var url = STREAM_URL + "?d=" + encodeURIComponent(d) + "&e=" + name + "&exp=" + exp +
    "&sig=" + hmac("event|" + name + "|" + d + "|" + exp);
  return new Promise(function (resolve) {
    var done = false;
    function finish(result) {
      if (done) return;
      done = true;
      console.log(JSON.stringify({ report: name, result: result }));
      resolve();
    }
    setTimeout(function () { finish("timeout"); }, REPORT_TIMEOUT_MS);
    try {
      var req = https.request(url, { method: "POST", headers: { "Content-Length": 0, "User-Agent": "alexa-via-airplay-skill" } }, function (res) {
        res.resume();
        finish(res.statusCode);
      });
      req.on("error", function (err) { finish(err.message); });
      req.end();
    } catch (err) {
      finish(String(err));
    }
  });
}

// Every Play (launch, resume, play button) gets a fresh URL.
function play(event) {
  var url = signedUrl(event);
  return {
    version: "1.0",
    response: {
      shouldEndSession: true,
      directives: [
        {
          type: "AudioPlayer.Play",
          playBehavior: "REPLACE_ALL",
          audioItem: { stream: { url: url, token: "airplay-" + Date.now(), offsetInMilliseconds: 0 } }
        }
      ]
    }
  };
}

function stop() {
  return { version: "1.0", response: { shouldEndSession: true, directives: [{ type: "AudioPlayer.Stop" }] } };
}

function say(text) {
  return { version: "1.0", response: { shouldEndSession: true, outputSpeech: { type: "PlainText", text: text } } };
}

// AudioPlayer and PlaybackController requests must not contain speech.
var EMPTY = { version: "1.0", response: {} };

// The user paused or resumed on the Echo: report first, so the bridge pauses
// or resumes the phone, then answer.
function pauseByUser(event) {
  return report(event, "paused").then(stop);
}

function resumeByUser(event) {
  return report(event, "resumed").then(function () { return play(event); });
}

exports.handler = async function (event) {
  var request = event.request || {};
  var intentName = request.intent && request.intent.name;
  console.log(JSON.stringify({ type: request.type, intent: intentName, error: request.error }));

  switch (request.type) {
    case "LaunchRequest":
      return play(event);
    case "PlaybackController.PlayCommandIssued":
      return resumeByUser(event);
    case "IntentRequest":
      switch (intentName) {
        case "PlayIntent":
        case "AMAZON.ResumeIntent":
        case "AMAZON.StartOverIntent":
          return resumeByUser(event);
        case "AMAZON.PauseIntent":
        case "AMAZON.StopIntent":
        case "AMAZON.CancelIntent":
          return pauseByUser(event);
        case "AMAZON.HelpIntent":
          return say("This speaker plays what you send to it with AirPlay. Start AirPlay on your phone or computer.");
        default:
          return EMPTY;
      }
    case "PlaybackController.PauseCommandIssued":
      return pauseByUser(event);
    case "AudioPlayer.PlaybackStarted":
      await report(event, "started");
      return EMPTY;
    case "AudioPlayer.PlaybackStopped":
      await report(event, "stopped");
      return EMPTY;
    case "AudioPlayer.PlaybackFailed":
      await report(event, "failed");
      return EMPTY;
    default:
      // Other AudioPlayer.* and PlaybackController.* requests, SessionEndedRequest,
      // System.ExceptionEncountered (logged above, see CloudWatch)
      return EMPTY;
  }
};
`;
}

const BUILT_IN_INTENTS = [
  "AMAZON.CancelIntent", "AMAZON.HelpIntent", "AMAZON.StopIntent", "AMAZON.NavigateHomeIntent",
  "AMAZON.FallbackIntent", "AMAZON.PauseIntent", "AMAZON.ResumeIntent", "AMAZON.NextIntent",
  "AMAZON.PreviousIntent", "AMAZON.StartOverIntent", "AMAZON.RepeatIntent", "AMAZON.LoopOnIntent",
  "AMAZON.LoopOffIntent", "AMAZON.ShuffleOnIntent", "AMAZON.ShuffleOffIntent",
];

export function interactionModel(invocationName: string): string {
  const model = {
    interactionModel: {
      languageModel: {
        invocationName: validateInvocationName(invocationName),
        intents: [
          { name: "PlayIntent", samples: ["play", "start", "start playing", "resume playing"] },
          ...BUILT_IN_INTENTS.map((name) => ({ name, samples: [] })),
        ],
        types: [],
      },
    },
  };
  return `${JSON.stringify(model, null, 2)}\n`;
}

/** The phrase the bridge sends as a text command to start the skill on an Echo. */
export function launchPhrase(invocationName: string): string {
  return `open ${validateInvocationName(invocationName)}`;
}
