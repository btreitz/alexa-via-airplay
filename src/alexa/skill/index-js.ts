import { URL_TTL_SECONDS } from "../../public/constants.ts";
import { SKILL_REPORT_TIMEOUT_MS } from "../constants.ts";
import type { SkillOptions } from "../types.ts";
import { streamUrl } from "../../public/url/base-url.ts";

// The developer console rejects optional chaining and the runtime is Node 16: keep the generated code plain ES5-style.
export function skillIndexJs({ publicBaseUrl, secret }: SkillOptions): string {
  return `// Generated by alexa-via-airplay. Paste into lambda/index.js, then Save and Deploy.
// Regenerate it when the URL or the secret changes. Keep this code private:
// the secret below lets anyone sign stream URLs.

var crypto = require("crypto");
var https = require("https");

var STREAM_URL = ${JSON.stringify(streamUrl(publicBaseUrl))};
var SECRET = ${JSON.stringify(secret)};
var URL_TTL_SECONDS = ${URL_TTL_SECONDS};
var REPORT_TIMEOUT_MS = ${SKILL_REPORT_TIMEOUT_MS};

function deviceSuffix(event) {
  var system = (event.context && event.context.System) || {};
  var deviceId = (system.device && system.device.deviceId) || "unknown";
  return deviceId.slice(-16);
}

function hmac(message) {
  return crypto.createHmac("sha256", SECRET).update(message).digest("base64")
    .replace(/\\+/g, "-").replace(/\\//g, "_").replace(/=+$/, "");
}

function expiry() {
  return Math.floor(Date.now() / 1000) + URL_TTL_SECONDS;
}

function signedUrl(event) {
  var d = deviceSuffix(event);
  var exp = expiry();
  return STREAM_URL + "?d=" + encodeURIComponent(d) + "&exp=" + exp + "&sig=" + hmac(d + "|" + exp);
}

function reportUrl(event, name) {
  var d = deviceSuffix(event);
  var exp = expiry();
  return STREAM_URL + "?d=" + encodeURIComponent(d) + "&e=" + name + "&exp=" + exp +
    "&sig=" + hmac("event|" + name + "|" + d + "|" + exp);
}

function report(event, name) {
  var url = reportUrl(event, name);
  return new Promise(function (resolve) {
    var done = false;
    function finish(result) {
      if (done) return;
      done = true;
      console.log(JSON.stringify({ report: name, result: result }));
      resolve();
    }
    setTimeout(function () { finish("timeout"); }, REPORT_TIMEOUT_MS);
    try {
      var req = https.request(url, { method: "POST", headers: { "Content-Length": 0, "User-Agent": "alexa-via-airplay-skill" } }, function (res) {
        res.resume();
        finish(res.statusCode);
      });
      req.on("error", function (err) { finish(err.message); });
      req.end();
    } catch (err) {
      finish(String(err));
    }
  });
}

function play(event) {
  return {
    version: "1.0",
    response: {
      shouldEndSession: true,
      directives: [
        {
          type: "AudioPlayer.Play",
          playBehavior: "REPLACE_ALL",
          audioItem: { stream: { url: signedUrl(event), token: "airplay-" + Date.now(), offsetInMilliseconds: 0 } }
        }
      ]
    }
  };
}

function stop() {
  return { version: "1.0", response: { shouldEndSession: true, directives: [{ type: "AudioPlayer.Stop" }] } };
}

function say(text) {
  return { version: "1.0", response: { shouldEndSession: true, outputSpeech: { type: "PlainText", text: text } } };
}

var EMPTY = { version: "1.0", response: {} };

function pauseByUser(event) {
  return report(event, "paused").then(stop);
}

function resumeByUser(event) {
  return report(event, "resumed").then(function () { return play(event); });
}

function onIntent(event, intentName) {
  switch (intentName) {
    case "PlayIntent":
    case "AMAZON.ResumeIntent":
    case "AMAZON.StartOverIntent":
      return resumeByUser(event);
    case "AMAZON.PauseIntent":
    case "AMAZON.StopIntent":
    case "AMAZON.CancelIntent":
      return pauseByUser(event);
    case "AMAZON.HelpIntent":
      return say("This speaker plays what you send to it with AirPlay. Start AirPlay on your phone or computer.");
    default:
      return EMPTY;
  }
}

function reportOnly(event, name) {
  return report(event, name).then(function () { return EMPTY; });
}

exports.handler = async function (event) {
  var request = event.request || {};
  var intentName = request.intent && request.intent.name;
  console.log(JSON.stringify({ type: request.type, intent: intentName, error: request.error }));

  switch (request.type) {
    case "LaunchRequest":
      return play(event);
    case "PlaybackController.PlayCommandIssued":
      return resumeByUser(event);
    case "IntentRequest":
      return onIntent(event, intentName);
    case "PlaybackController.PauseCommandIssued":
      return pauseByUser(event);
    case "AudioPlayer.PlaybackStarted":
      return reportOnly(event, "started");
    case "AudioPlayer.PlaybackStopped":
      return reportOnly(event, "stopped");
    case "AudioPlayer.PlaybackFailed":
      return reportOnly(event, "failed");
    default:
      return EMPTY;
  }
};
`;
}
