import { EVENT_BUS_HOST, SAMPLE_RATE, SHAIRPORT_NQPTP_NAME_MAX } from "../constants.ts";
import { receiverId } from "./ids.ts";
import type { MqttTarget, ShairportConfigOptions } from "../types.ts";

function quote(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function generalSection({ entry }: ShairportConfigOptions): string[] {
  const nqptpName = `/nqptp-${receiverId(entry.serial)}`.slice(0, SHAIRPORT_NQPTP_NAME_MAX);
  return [
    "general = {",
    `  name = ${quote(entry.name)};`,
    `  port = ${entry.port};`,
    '  output_backend = "pipe";',
    '  mdns_backend = "avahi";',
    `  nqptp_shared_memory_interface_name = ${quote(nqptpName)};`,
    `  airplay_device_id = 0x${entry.airplayDeviceId}L;`,
    '  ignore_volume_control = "yes";',
    "};",
    "",
  ];
}

function pipeSection(fifo: string): string[] {
  return [
    "pipe = {",
    `  name = ${quote(fifo)};`,
    `  output_rate = ${SAMPLE_RATE};`,
    '  output_format = "S16_LE";',
    "};",
    "",
  ];
}

function mqttSections(mqtt: MqttTarget): string[] {
  return [
    "metadata = {",
    '  enabled = "yes";',
    '  include_cover_art = "no";',
    '  cover_art_cache_directory = "";',
    "};",
    "",
    "mqtt = {",
    '  enabled = "yes";',
    `  hostname = ${quote(EVENT_BUS_HOST)};`,
    `  port = ${mqtt.port};`,
    `  topic = ${quote(mqtt.topic)};`,
    '  publish_parsed = "yes";',
    '  publish_raw = "yes";',
    '  publish_cover = "no";',
    '  enable_remote = "yes";',
    "};",
    "",
  ];
}

export function shairportConfig(options: ShairportConfigOptions): string {
  return [
    "// Generated by alexa-via-airplay. Changes are overwritten.",
    ...generalSection(options),
    ...pipeSection(options.fifo),
    ...(options.mqtt ? mqttSections(options.mqtt) : []),
  ].join("\n");
}
