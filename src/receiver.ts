// One AirPlay 2 receiver for one Echo: a Shairport Sync process writing raw
// PCM into a FIFO, and the MP3 broadcaster that reads it.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { Mp3Broadcaster, PcmInput, BYTES_PER_SECOND } from "./audio.ts";
import type { ReceiverEntry } from "./state.ts";
import { Supervised } from "./supervisor.ts";

/** Short, filesystem- and shm-safe ID derived from the Echo serial. */
export function receiverId(serial: string): string {
  return serial.toLowerCase().replace(/[^a-z0-9]/g, "").slice(-24) || "echo";
}

/** Stable, locally administered MAC-style AirPlay device ID for a serial. */
export function airplayDeviceIdFor(serial: string): string {
  const bytes = crypto.createHash("sha256").update(`alexa-via-airplay:${serial}`).digest().subarray(0, 6);
  bytes[0] = (bytes[0] & 0xfc) | 0x02;
  return bytes.toString("hex").toUpperCase();
}

function quote(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

export interface ShairportConfigOptions {
  entry: ReceiverEntry;
  fifo: string;
  /** Per-receiver MQTT topic on the bridge's internal broker (session events, remote control). */
  mqtt?: { port: number; topic: string };
}

export function shairportConfig({ entry, fifo, mqtt }: ShairportConfigOptions): string {
  const id = receiverId(entry.serial);
  const lines = [
    "// Generated by alexa-via-airplay. Changes are overwritten.",
    "general = {",
    `  name = ${quote(entry.name)};`,
    `  port = ${entry.port};`,
    '  output_backend = "pipe";',
    '  mdns_backend = "avahi";',
    `  nqptp_shared_memory_interface_name = ${quote(`/nqptp-${id}`.slice(0, 63))};`,
    `  airplay_device_id = 0x${entry.airplayDeviceId}L;`,
    // The Echo applies the volume; the PCM stays at full scale.
    '  ignore_volume_control = "yes";',
    "};",
    "",
    "pipe = {",
    `  name = ${quote(fifo)};`,
    "  output_rate = 44100;",
    '  output_format = "S16_LE";',
    "};",
    "",
  ];
  if (mqtt) {
    lines.push(
      "metadata = {",
      '  enabled = "yes";',
      '  include_cover_art = "no";',
      '  cover_art_cache_directory = "";',
      "};",
      "",
      "mqtt = {",
      '  enabled = "yes";',
      '  hostname = "127.0.0.1";',
      `  port = ${mqtt.port};`,
      `  topic = ${quote(mqtt.topic)};`,
      '  publish_parsed = "yes";',
      '  publish_raw = "no";',
      '  publish_cover = "no";',
      '  enable_remote = "yes";',
      "};",
      "",
    );
  }
  return lines.join("\n");
}

export interface ReceiverStatus {
  id: string;
  serial: string;
  name: string;
  port: number;
  process: { running: boolean; restarts: number } | null;
  audio: { active: boolean; secondsTotal: number; lastAudioSecondsAgo: number | null; levelDb: number | null };
  listeners: { remote: string | null; userAgent: string | null; seconds: number }[];
}

export interface ReceiverOptions {
  entry: ReceiverEntry;
  runDir: string;
  /** Start Shairport Sync. Off for development without it. */
  runShairport: boolean;
  mqtt?: { port: number; topic: string };
}

export class Receiver {
  readonly id: string;
  entry: ReceiverEntry;
  readonly input: PcmInput;
  readonly stream: Mp3Broadcaster;
  private readonly shairport?: Supervised;
  private readonly confFile: string;
  private readonly options: ReceiverOptions;
  /** Set from Shairport Sync's session events once they're wired up; null = unknown. */
  airplaySession: boolean | null = null;

  constructor(options: ReceiverOptions) {
    this.options = options;
    this.entry = options.entry;
    this.id = receiverId(options.entry.serial);
    const pipes = path.join(options.runDir, "pipes");
    const confs = path.join(options.runDir, "shairport");
    fs.mkdirSync(pipes, { recursive: true });
    fs.mkdirSync(confs, { recursive: true });
    this.confFile = path.join(confs, `${this.id}.conf`);
    this.input = new PcmInput(path.join(pipes, this.id));
    this.stream = new Mp3Broadcaster(this.id, this.input);
    if (options.runShairport) {
      this.shairport = new Supervised({
        name: `airplay:${this.id}`,
        command: "shairport-sync",
        args: ["-c", this.confFile],
        beforeStart: () => this.writeConfig(),
        onLine: (line) => !/^\s*$/.test(line),
      });
    }
  }

  start(): void {
    this.input.open();
    this.writeConfig();
    this.shairport?.start();
  }

  async stop(): Promise<void> {
    await this.shairport?.stop();
    this.stream.close();
    this.input.close();
    fs.rmSync(this.confFile, { force: true });
  }

  /** Applies a changed name (or port): Shairport Sync needs a restart for that. */
  async update(entry: ReceiverEntry): Promise<void> {
    const changed = entry.name !== this.entry.name || entry.port !== this.entry.port;
    this.entry = entry;
    if (changed && this.shairport) {
      await this.shairport.stop();
      this.shairport.start();
    }
  }

  get lastAudioAt(): number {
    return this.input.lastDataAt;
  }

  get serial(): string {
    return this.entry.serial;
  }

  setAirplaySession(active: boolean | null): void {
    this.airplaySession = active;
  }

  /**
   * Whether an AirPlay sender is (still) using this receiver: the session
   * flag when known, otherwise audio within the idle window.
   */
  sessionActive(idleMs: number): boolean {
    if (this.airplaySession !== null) return this.airplaySession;
    return this.input.lastDataAt > 0 && Date.now() - this.input.lastDataAt <= idleMs;
  }

  private writeConfig(): void {
    fs.writeFileSync(this.confFile, shairportConfig({ entry: this.entry, fifo: this.input.fifo, mqtt: this.options.mqtt }));
  }

  status(): ReceiverStatus {
    const now = Date.now();
    return {
      id: this.id,
      serial: this.entry.serial,
      name: this.entry.name,
      port: this.entry.port,
      process: this.shairport ? { running: this.shairport.running, restarts: this.shairport.restarts } : null,
      audio: {
        active: this.input.active,
        secondsTotal: Math.round(this.input.bytesTotal / BYTES_PER_SECOND),
        lastAudioSecondsAgo: this.input.lastDataAt ? Math.round((now - this.input.lastDataAt) / 1000) : null,
        levelDb: this.input.levelDb,
      },
      listeners: this.stream.clientList.map((c) => ({
        remote: c.remote,
        userAgent: c.userAgent,
        seconds: Math.round((now - c.connectedAt) / 1000),
      })),
    };
  }
}
